static void Motor_SetSpeed(uint8_t motor_index, int16_t duty_ticks)
{
  uint32_t duty;
  const MotorChannel_t *motor;

  if (motor_index >= (sizeof(motors) / sizeof(motors[0])))
  {
    return;
  }

  if (duty_ticks > (int16_t)PWM_MAX_DUTY_TICKS)
  {
    duty_ticks = (int16_t)PWM_MAX_DUTY_TICKS;
  }
  else if (duty_ticks < -(int16_t)PWM_MAX_DUTY_TICKS)
  {
    duty_ticks = -(int16_t)PWM_MAX_DUTY_TICKS;
  }

  motor = &motors[motor_index];
  duty = (duty_ticks < 0) ? (uint32_t)(-duty_ticks) : (uint32_t)duty_ticks;

  if (duty_ticks > 0)
  {
    __HAL_TIM_SET_COMPARE(motor->in1_timer, motor->in1_channel, duty);
    __HAL_TIM_SET_COMPARE(motor->in2_timer, motor->in2_channel, 0U);
  }
  else if (duty_ticks < 0)
  {
    __HAL_TIM_SET_COMPARE(motor->in1_timer, motor->in1_channel, 0U);
    __HAL_TIM_SET_COMPARE(motor->in2_timer, motor->in2_channel, duty);
  }
  else
  {
    __HAL_TIM_SET_COMPARE(motor->in1_timer, motor->in1_channel, 0U);
    __HAL_TIM_SET_COMPARE(motor->in2_timer, motor->in2_channel, 0U);
  }
}

static void Motor_SetPercent(uint8_t motor_index, int8_t duty_percent)
{
  int16_t duty_ticks;

  if (duty_percent > 100)
  {
    duty_percent = 100;
  }
  else if (duty_percent < -100)
  {
    duty_percent = -100;
  }

  duty_ticks = (int16_t)(((int32_t)duty_percent * (int32_t)PWM_MAX_DUTY_TICKS) / 100);
  Motor_SetSpeed(motor_index, duty_ticks);
}

static void Motor_CoastAll(void)
{
  uint8_t motor_index;

  for (motor_index = 0U; motor_index < (sizeof(motors) / sizeof(motors[0])); motor_index++)
  {
    Motor_SetSpeed(motor_index, 0);
  }
}

